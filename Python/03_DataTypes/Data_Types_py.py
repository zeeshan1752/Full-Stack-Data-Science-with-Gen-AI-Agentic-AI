# Integer
age = 21
print(age)
print(type(age))

# Float
height = 5.8
print(height)
print(type(height))

# Boolean
is_student = True
print(is_student)
print(type(is_student))

# Complex
x = 3 + 4j
y = 5 - 2J

print(x)
print(y)
print(type(x))

print(x.real)
print(x.imag)

# String
name = "Python"
print(name)
print(type(name))

# type() function
print(type(100))
print(type(10.5))
print(type(True))
print(type(3 + 4j))
print(type("Python"))

# id() function
a = 10
b = a

print(id(a))
print(id(b))