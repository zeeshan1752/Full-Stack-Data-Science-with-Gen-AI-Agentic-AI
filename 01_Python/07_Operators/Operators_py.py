# Python Operators - Practice

# 1. Arithmetic Operators

a = 10
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)


# 2. Assignment Operators

a = 10

a += 5
print(a)

a -= 5
print(a)

a *= 5
print(a)

a /= 5
print(a)

a //= 2
print(a)

a %= 3
print(a)

a **= 2
print(a)


# 3. Relational Operators

a = 10
b = 5

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)


# 4. Logical Operators

a = 10
b = 5

print(a > 5 and b < 10)
print(a > 5 or b > 10)
print(not(a > 5))


# 5. Unary Operators

a = 10

print(+a)
print(-a)