# NUMBER SYSTEM - PYTHON PRACTICE

# 1. Decimal to Binary
decimal = 10
binary = bin(decimal)

print("Decimal:", decimal)
print("Binary:", binary)


# 2. Binary to Decimal
binary = "1010"
decimal = int(binary, 2)

print("Binary:", binary)
print("Decimal:", decimal)


# 3. Decimal to Octal
decimal = 10
octal = oct(decimal)

print("Decimal:", decimal)
print("Octal:", octal)


# 4. Octal to Decimal
octal = "12"
decimal = int(octal, 8)

print("Octal:", octal)
print("Decimal:", decimal)


# 5. Decimal to Hexadecimal
decimal = 10
hexadecimal = hex(decimal)

print("Decimal:", decimal)
print("Hexadecimal:", hexadecimal)


# 6. Hexadecimal to Decimal
hexadecimal = "A"
decimal = int(hexadecimal, 16)

print("Hexadecimal:", hexadecimal)
print("Decimal:", decimal)